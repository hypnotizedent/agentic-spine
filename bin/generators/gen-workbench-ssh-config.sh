#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
CONTRACT_FILE="$ROOT/ops/bindings/workbench.ssh.attach.contract.yaml"
BINDING_FILE="$ROOT/ops/bindings/ssh.targets.yaml"
MODE="write"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --write)
      MODE="write"
      shift
      ;;
    --check)
      MODE="check"
      shift
      ;;
    -h|--help)
      cat <<'EOF'
gen-workbench-ssh-config.sh - Materialize workbench SSH projection from spine ssh.targets

Usage:
  ./bin/generators/gen-workbench-ssh-config.sh --write
  ./bin/generators/gen-workbench-ssh-config.sh --check

Defaults to --write when no mode is provided.
EOF
      exit 0
      ;;
    *)
      echo "ERROR: unknown argument: $1" >&2
      exit 2
      ;;
  esac
done

[[ -f "$CONTRACT_FILE" ]] || {
  echo "ERROR: missing contract file: $CONTRACT_FILE" >&2
  exit 1
}
[[ -f "$BINDING_FILE" ]] || {
  echo "ERROR: missing SSH binding: $BINDING_FILE" >&2
  exit 1
}

python3 - "$MODE" "$ROOT" "$CONTRACT_FILE" "$BINDING_FILE" <<'PY'
import os
import shlex
import sys
import tempfile
from pathlib import Path

import yaml


def render_extra_opts(raw: str) -> list[str]:
    if not raw:
        return []

    tokens = shlex.split(raw)
    lines: list[str] = []
    idx = 0
    while idx < len(tokens):
        token = tokens[idx]
        opt = ""
        if token == "-o" and idx + 1 < len(tokens):
            opt = tokens[idx + 1]
            idx += 2
        elif token.startswith("-o") and len(token) > 2:
            opt = token[2:]
            idx += 1
        else:
            idx += 1
            continue

        if "=" in opt:
            key, value = opt.split("=", 1)
            lines.append(f"    {key} {value}")
        elif opt:
            lines.append(f"    {opt}")

    return lines


def render_block(target: dict, hostname: str, *, include_proxyjump: bool) -> str:
    aliases = [str(target.get("id", "")).strip()]
    aliases.extend(
        str(alias).strip()
        for alias in (target.get("aliases") or [])
        if str(alias).strip()
    )
    aliases = [alias for alias in aliases if alias]

    user = str(target.get("user") or "root").strip() or "root"
    lines = [
        f"Host {' '.join(aliases)}",
        f"    HostName {hostname}",
        f"    User {user}",
    ]

    probe_via = str(target.get("probe_via") or "").strip()
    if include_proxyjump and probe_via:
        lines.append(f"    ProxyJump {probe_via}")

    lines.append("    IdentityFile ~/.ssh/id_ed25519")
    lines.extend(render_extra_opts(str(target.get("ssh_extra_opts") or "").strip()))
    lines.append("")
    return "\n".join(lines)


mode = sys.argv[1]
root = Path(sys.argv[2])
contract_path = Path(sys.argv[3])
binding_path = Path(sys.argv[4])


def canonical_display_root(path: Path) -> Path:
    text = str(path)
    marker = "/.runtime/spine/tmp/worktrees/agentic-spine/"
    if marker in text:
        workspace_root = text.split(marker, 1)[0]
        return Path(workspace_root) / "agentic-spine"
    return path

contract = yaml.safe_load(contract_path.read_text(encoding="utf-8")) or {}
binding = yaml.safe_load(binding_path.read_text(encoding="utf-8")) or {}
ssh_root = binding.get("ssh") or {}
targets = ssh_root.get("targets") or []

workbench_root_raw = str(contract.get("workbench_root") or "").strip()
if not workbench_root_raw:
    raise SystemExit(f"ERROR: workbench_root missing in {contract_path}")
workbench_root = Path(os.path.expanduser(workbench_root_raw))

output_rel = str(contract.get("workbench_ssh_config") or "dotfiles/ssh/config.d/tailscale.conf").strip()
renderer_rel = str(contract.get("generator_script") or "bin/generators/gen-workbench-ssh-config.sh").strip()
output_path = workbench_root / output_rel
renderer_path = root / renderer_rel
display_root = canonical_display_root(root)
display_binding_path = display_root / "ops" / "bindings" / "ssh.targets.yaml"
display_renderer_path = display_root / renderer_rel

if not workbench_root.is_dir():
    raise SystemExit(f"ERROR: workbench root not found: {workbench_root}")

tailscale_targets: list[dict] = []
lan_only_targets: list[dict] = []
for raw in targets:
    if not isinstance(raw, dict):
        continue
    target = dict(raw)
    target_id = str(target.get("id") or "").strip()
    host = str(target.get("host") or "").strip()
    tailscale_ip = str(target.get("tailscale_ip") or "").strip()
    policy = str(target.get("access_policy") or "lan_first").strip() or "lan_first"

    if not target_id:
        continue

    if policy == "lan_only":
        if host:
            lan_only_targets.append(target)
        continue

    preferred = tailscale_ip or host
    if preferred:
        target["_projected_hostname"] = preferred
        tailscale_targets.append(target)

header = [
    "# SSH Host Projection (generated)",
    f"# Source of truth: {display_binding_path}",
    f"# Renderer: {display_renderer_path}",
    "# Do not edit this file manually.",
    "#",
    "# Projection rules:",
    "# - lan_first targets use Tailscale IPs for location-agnostic human SSH.",
    "# - tailscale_required targets use their Tailscale IPs directly.",
    "# - lan_only targets stay on LAN IPs and ProxyJump via probe_via when declared.",
    "",
    "# Tailscale-first host inventory",
]

content_lines = header[:]
for target in tailscale_targets:
    content_lines.append(
        render_block(target, str(target["_projected_hostname"]), include_proxyjump=False)
    )

if lan_only_targets:
    content_lines.append("# LAN-only targets routed via declared jump hosts")
    for target in lan_only_targets:
        content_lines.append(
            render_block(target, str(target.get("host") or "").strip(), include_proxyjump=True)
        )

content = "\n".join(content_lines).rstrip() + "\n"

if mode == "check":
    existing = output_path.read_text(encoding="utf-8") if output_path.exists() else ""
    if existing == content:
        print(f"OK {output_path}")
        raise SystemExit(0)
    print(f"DRIFT {output_path}")
    raise SystemExit(1)

output_path.parent.mkdir(parents=True, exist_ok=True)
with tempfile.NamedTemporaryFile("w", delete=False, encoding="utf-8", dir=str(output_path.parent)) as handle:
    handle.write(content)
    tmp_path = Path(handle.name)

os.replace(tmp_path, output_path)
os.chmod(output_path, 0o644)
print(output_path)
PY
